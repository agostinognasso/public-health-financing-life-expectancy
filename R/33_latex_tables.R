# 33: LaTeX bodies of Tables 1 and 3
#
# Prints the tabular environments to the log, with the Fieller sets
# and the diagnostics that go in the note to Table 3.
#
# Reads  output/shocks_panel.rds; data/ through build_panel()
# Writes log/33_latex_tables.log only
source("00_common.R")
suppressPackageStartupMessages(library(plm))

dat <- build_panel(zero_rule = "multiplicative")
# HIV prevalence is described on the observations where it is reported
shk <- readRDS(file.path(OUT, "shocks_panel.rds"))
dat <- dat %>% left_join(shk %>% dplyr::select(iso3c, year, HIV_pct),
                         by = c("iso3c", "year"))

# ---- Table 1 -----------------------------------------------
# financing components before zero replacement
V <- list(
  c("LE",         "Life expectancy (years)"),
  c("log_GNI",    "Log income per head (constant 2015 US\\$)"),
  c("c_PUB",      "Public share (\\% of CHE)"),
  c("c_OOP",      "Out-of-pocket (\\% of CHE)"),
  c("c_PNO",      "Private non-out-of-pocket (\\% of CHE)"),
  c("c_EXT",      "External (\\% of CHE)"),
  c("EDU_GROSS",  "Secondary gross enrolment (\\%)"),
  c("IMM_DPT",    "Immunisation, DPT coverage (\\%)"),
  c("SANITATION", "Basic sanitation access (\\%)"),
  c("HIV_pct",    "HIV prevalence, adults 15--49 (\\%)"))

rows <- lapply(V, function(z) {
  x <- dat[[z[1]]]; g <- dat$iso3c
  ok <- !is.na(x); x <- x[ok]; g <- g[ok]
  mu <- tapply(x, g, mean); cm <- as.numeric(mu[as.character(g)])
  data.frame(lab = z[2], n = length(x), med = median(x),
             q1 = quantile(x, .25), q3 = quantile(x, .75),
             mn = min(x), mx = max(x),
             sdb = sd(mu), sdw = sd(x - cm), row.names = NULL)
})
t1 <- bind_rows(rows)

dec <- function(v, d) formatC(v, format = "f", digits = d)
t1$d <- ifelse(t1$lab %in% c("Log income per head (constant 2015 US\\$)",
                             "HIV prevalence, adults 15--49 (\\%)"), 2, 1)

cat("%% ---- Table 1, generated by R/33_latex_tables.R ----\n")
cat("\\begin{tabular}{@{\\extracolsep\\fill}lrrrrrrr@{}}\n\\toprule\n")
cat("Variable & $n$ & Min & Q1 & Median & Q3 & Max &",
    "\\multicolumn{1}{c}{SD} \\\\\n")
cat("& & & & & & & \\multicolumn{1}{c}{between / within} \\\\\n\\midrule\n")
for (i in seq_len(nrow(t1))) {
  d <- t1$d[i]
  cat(sprintf("%-46s & %d & %s & %s & %s & %s & %s & %s / %s \\\\\n",
              t1$lab[i], t1$n[i], dec(t1$mn[i], d), dec(t1$q1[i], d),
              dec(t1$med[i], d), dec(t1$q3[i], d), dec(t1$mx[i], d),
              dec(t1$sdb[i], d), dec(t1$sdw[i], d)))
}
cat("\\botrule\n\\end{tabular}\n")

# ---- Table 3 -----------------------------------------------
cat("\n\n%% ---- Table 3, generated by R/33_latex_tables.R ----\n")
pd <- pdata.frame(dat, index = c("iso3c", "year"))
m <- pgmm(LE ~ lag(LE, 1) + log_GNI + EDU_GROSS + PUB + OOP_share +
            IMM_DPT + SANITATION | lag(LE, 2:5),
          data = pd, effect = "twoways", model = "twosteps",
          transformation = "ld", collapse = TRUE)
b <- coef(m); Vc <- pgmm_vcov(m)
lr   <- longrun(b, Vc, "lag(LE, 1)")
lr90 <- longrun(b, Vc, "lag(LE, 1)", level = 0.90)
lv   <- fieller_levels(b, Vc, "lag(LE, 1)")

LAB <- c("lag(LE, 1)" = "Life expectancy, lagged one year",
         "log_GNI"    = "Log income per head",
         "IMM_DPT"    = "Immunisation",
         "EDU_GROSS"  = "Secondary enrolment",
         "SANITATION" = "Sanitation",
         "PUB"        = "Public share of CHE",
         "OOP_share"  = "Out-of-pocket share of CHE")
ORD <- names(LAB)

st <- function(x) ifelse(x < 0.01, "\\textsuperscript{\\textdagger}", "")
# long run: the point estimate and its 90 per cent Fieller interval.
# Every Fieller set is an interval only up to level_bounded, below 95
# per cent, so the 95 per cent sets are described in the note.
cat("\\begin{tabular}{@{\\extracolsep\\fill}lrrrrr@{}}\n\\toprule\n")
cat("Variable & $\\hat{\\beta}$ & SE & 95\\% CI &",
    "$\\hat{\\beta}_{\\mathrm{LR}}$ & 90\\% Fieller interval \\\\\n\\midrule\n")
for (tn in ORD) {
  est <- b[[tn]]; se <- sqrt(Vc[tn, tn]); p <- 2 * pnorm(-abs(est / se))
  lo <- est - 1.96 * se; hi <- est + 1.96 * se
  if (tn == "lag(LE, 1)") {
    lrs <- "--- & ---"
  } else {
    r <- lr90[lr90$term == tn, ]
    stopifnot(r$fieller_type == "bounded")
    lrs <- sprintf("$%+.3f$ & $[%+.3f,\\ %+.3f]$", r$beta_LR,
                   r$fieller_lo, r$fieller_hi)
  }
  cat(sprintf("%-34s & $%+.4f$%s & %.4f & $[%+.4f,\\ %+.4f]$ & %s \\\\\n",
              LAB[[tn]], est, st(p), se, lo, hi, lrs))
}
cat("\\botrule\n\\end{tabular}\n")

cat("\n%% Fieller sets for the table note:\n")
cat(sprintf("%% every set is an interval up to the %.1f%% level\n",
            100 * lv$level_bounded[1]))
for (tn in setdiff(ORD, "lag(LE, 1)")) {
  r <- lr[lr$term == tn, ]
  cat(sprintf("%% %-11s 95%%: %s; whole line from the %.2f%% level\n", tn,
              fmt_fieller(r$fieller_lo, r$fieller_hi, r$fieller_type, 3),
              100 * lv$level_wholeline[lv$term == tn]))
}

cat("\n%% diagnostics for the table note:\n")
sg <- sargan(m)
cat(sprintf("%% Hansen J = %.2f, df = %d, p = %.3f\n",
            sg$statistic, sg$parameter, sg$p.value))
for (k in 1:3) { a <- mtest(m, order = k)
  cat(sprintf("%% AR(%d) p = %.3f\n", k, a$p.value)) }
cat(sprintf("%% instruments = %d\n", dim(m$W[[1]])[2]))
cat(sprintf("%% alpha = %.4f (SE %.4f); 1-alpha = %.4f, 95%% CI [%.4f, %.4f]\n",
            b[["lag(LE, 1)"]], sqrt(Vc["lag(LE, 1)", "lag(LE, 1)"]),
            1 - b[["lag(LE, 1)"]],
            1 - b[["lag(LE, 1)"]] - 1.96 * sqrt(Vc["lag(LE, 1)", "lag(LE, 1)"]),
            1 - b[["lag(LE, 1)"]] + 1.96 * sqrt(Vc["lag(LE, 1)", "lag(LE, 1)"])))
